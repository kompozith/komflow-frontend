/**
 * Pre-compiles src/styles/tailwind.css (Tailwind directives + our @theme/design-system
 * classes) into plain CSS at src/styles/tailwind.compiled.css.
 *
 * Why this exists: Angular's esbuild-based application builder correctly runs
 * PostCSS + @tailwindcss/postcss on this file (confirmed via internal debug
 * logging — the onLoad callback returns the fully compiled CSS, responsive
 * variants included), but that compiled content never survives into the final
 * bundled styles.css — every tw:* utility and @theme token is silently absent
 * from the shipped output, with no build error or warning. Root cause not
 * isolated (behaves the same with cache cleared, ng serve stopped, and
 * optimization disabled) — most likely a bug in how the esbuild pipeline
 * merges CSS `@layer` output across multiple `styles` array entries. Rather
 * than depend on Angular's builder for this specific transform, this script
 * runs PostCSS directly and Angular's `styles` array points at its plain-CSS
 * output instead, which then passes straight through untouched.
 *
 * Run manually via `npm run build:css`, and automatically before `ng build`/
 * `ng serve` via the `prebuild-css`... actually wired as `pre`-hooks on the
 * `build`/`start` npm scripts — see package.json.
 */
import postcss from 'postcss';
import tailwindcss from '@tailwindcss/postcss';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const inputPath = path.join(projectRoot, 'src/styles/tailwind.css');
const outputPath = path.join(projectRoot, 'src/styles/tailwind.compiled.css');

const css = fs.readFileSync(inputPath, 'utf8');

postcss([tailwindcss()])
  .process(css, { from: inputPath, to: outputPath })
  .then((result) => {
    const banner = `/* AUTO-GENERATED by scripts/build-tailwind.mjs from tailwind.css — do not edit directly. */\n`;
    fs.writeFileSync(outputPath, banner + result.css);
    console.log(`[build-tailwind] Compiled ${inputPath} -> ${outputPath} (${result.css.length} bytes)`);
  })
  .catch((err) => {
    console.error('[build-tailwind] Compilation failed:', err);
    process.exit(1);
  });
